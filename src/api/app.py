"""
job-tracker API -- one Lambda behind an HTTP API.

  GET    /                 the web app (no data in it, no key needed)
  GET    /apps             list applications           \
  POST   /apps             add one                      |  require header
  PATCH  /apps/{id}        change status / notes        |  x-api-key
  DELETE /apps/{id}        remove one                  /

Personal tool, so auth is one shared key generated by Terraform. The page asks
for it once and keeps it in the browser.
"""
import base64
import hmac
import json
import os
import uuid
from datetime import datetime, timezone
from pathlib import Path

import boto3
from botocore.exceptions import ClientError

TABLE = boto3.resource("dynamodb").Table(os.environ.get("TABLE_NAME", "job-tracker-apps"))
API_KEY = os.environ.get("API_KEY", "")
STALE_DAYS = int(os.environ.get("STALE_DAYS", "7"))

STATUSES = ["applied", "screen", "interview", "offer", "rejected", "ghosted"]
FIELDS = ("company", "role", "link", "location", "source", "notes", "applied_on")
PAGE = (Path(__file__).parent / "index.html").read_text()

if not API_KEY:
    print("CONFIG ERROR: API_KEY is not set. Every data request will be refused.")


def now():
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def resp(code, body):
    return {"statusCode": code, "headers": {"Content-Type": "application/json"},
            "body": json.dumps(body, default=str)}


def authorized(event):
    got = (event.get("headers") or {}).get("x-api-key", "")
    return bool(API_KEY) and hmac.compare_digest(got, API_KEY)


def body_of(event):
    raw = event.get("body") or "{}"
    if event.get("isBase64Encoded"):
        raw = base64.b64decode(raw).decode()
    try:
        data = json.loads(raw)
    except json.JSONDecodeError:
        return None
    return data if isinstance(data, dict) else None


def clean(data):
    out = {}
    for k in FIELDS:
        v = data.get(k)
        if isinstance(v, str):
            v = v.strip()[:500]
            if v:
                out[k] = v
    return out


def lambda_handler(event, context):
    route = event.get("routeKey", "")
    if route == "GET /":
        return {"statusCode": 200, "headers": {"Content-Type": "text/html; charset=utf-8"}, "body": PAGE}

    if not authorized(event):
        return resp(401, {"error": "missing or wrong access key"})

    app_id = (event.get("pathParameters") or {}).get("id")

    if route == "GET /apps":
        items, kwargs = [], {}
        while True:  # a personal list is small, so a scan is the right tool
            page = TABLE.scan(**kwargs)
            items += page.get("Items", [])
            if "LastEvaluatedKey" not in page:
                break
            kwargs["ExclusiveStartKey"] = page["LastEvaluatedKey"]
        items.sort(key=lambda i: i.get("applied_on", ""), reverse=True)
        return resp(200, {"apps": items, "statuses": STATUSES, "stale_days": STALE_DAYS})

    if route == "POST /apps":
        data = body_of(event)
        if data is None:
            return resp(400, {"error": "body must be a JSON object"})
        item = clean(data)
        if not item.get("company") or not item.get("role"):
            return resp(400, {"error": "company and role are required"})
        status = data.get("status", "applied")
        if status not in STATUSES:
            return resp(400, {"error": f"status must be one of {STATUSES}"})
        ts = now()
        item.update({
            "app_id": uuid.uuid4().hex[:10],
            "status": status,
            "applied_on": item.get("applied_on", ts[:10]),
            "created_at": ts,
            "updated_at": ts,
            "history": [{"status": status, "at": ts}],
        })
        TABLE.put_item(Item=item)
        return resp(201, item)

    if route == "PATCH /apps/{id}":
        data = body_of(event)
        if data is None:
            return resp(400, {"error": "body must be a JSON object"})
        sets, values, names = ["updated_at = :u"], {":u": now()}, {}
        for k, v in clean(data).items():
            sets.append(f"#{k} = :{k}")
            names[f"#{k}"] = k
            values[f":{k}"] = v
        if "status" in data:
            if data["status"] not in STATUSES:
                return resp(400, {"error": f"status must be one of {STATUSES}"})
            sets.append("#st = :s")
            names["#st"] = "status"
            values[":s"] = data["status"]
            # Every status change is recorded, so the weekly summary can count
            # real responses instead of guessing from the current status.
            sets.append("history = list_append(if_not_exists(history, :empty), :h)")
            values[":h"] = [{"status": data["status"], "at": values[":u"]}]
            values[":empty"] = []
        try:
            out = TABLE.update_item(
                Key={"app_id": app_id},
                UpdateExpression="SET " + ", ".join(sets),
                ConditionExpression="attribute_exists(app_id)",
                ExpressionAttributeValues=values,
                **({"ExpressionAttributeNames": names} if names else {}),
                ReturnValues="ALL_NEW",
            )
        except ClientError as e:
            if e.response["Error"]["Code"] == "ConditionalCheckFailedException":
                return resp(404, {"error": "no such application"})
            raise
        return resp(200, out["Attributes"])

    if route == "DELETE /apps/{id}":
        try:
            TABLE.delete_item(Key={"app_id": app_id}, ConditionExpression="attribute_exists(app_id)")
        except ClientError as e:
            if e.response["Error"]["Code"] == "ConditionalCheckFailedException":
                return resp(404, {"error": "no such application"})
            raise
        return resp(200, {"deleted": app_id})

    return resp(404, {"error": f"no route {route}"})
